from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from io import BytesIO
from datetime import datetime


SEVERITY_COLORS = {
    "critical": colors.HexColor("#dc2626"),
    "high": colors.HexColor("#ea580c"),
    "medium": colors.HexColor("#d97706"),
    "low": colors.HexColor("#16a34a"),
}


def generate_pdf_report(review: dict, username: str) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=2*cm, bottomMargin=2*cm)
    styles = getSampleStyleSheet()
    story = []

    title_style = ParagraphStyle("Title", parent=styles["Title"], fontSize=22, textColor=colors.HexColor("#1e40af"), spaceAfter=6)
    heading_style = ParagraphStyle("Heading", parent=styles["Heading2"], fontSize=13, textColor=colors.HexColor("#1e3a8a"), spaceBefore=12, spaceAfter=4)
    body_style = ParagraphStyle("Body", parent=styles["Normal"], fontSize=10, leading=14)
    code_style = ParagraphStyle("Code", parent=styles["Code"], fontSize=8, backColor=colors.HexColor("#f1f5f9"), leading=12)

    # Header
    story.append(Paragraph("AI Code Review Report", title_style))
    story.append(Paragraph(f"<b>Project:</b> {review.get('title', 'N/A')} &nbsp;&nbsp; <b>Language:</b> {review.get('language', 'N/A')}", body_style))
    story.append(Paragraph(f"<b>Reviewed by:</b> {username} &nbsp;&nbsp; <b>Date:</b> {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}", body_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#3b82f6"), spaceAfter=10))

    # Score
    score = review.get("overall_score", 0)
    score_color = "#16a34a" if score >= 7 else "#d97706" if score >= 4 else "#dc2626"
    story.append(Paragraph(f'Overall Score: <font color="{score_color}"><b>{score}/10</b></font>', heading_style))
    story.append(Paragraph(review.get("summary", ""), body_style))
    story.append(Spacer(1, 0.3*cm))

    # Bugs
    bugs = review.get("bugs", [])
    if bugs:
        story.append(Paragraph(f"Bugs & Issues ({len(bugs)} found)", heading_style))
        for bug in bugs:
            sev = bug.get("severity", "low").lower()
            color = SEVERITY_COLORS.get(sev, colors.gray)
            data = [
                [Paragraph(f'<b><font color="{color.hexval() if hasattr(color,"hexval") else "#000"}">[{sev.upper()}]</font> {bug.get("type","")}</b>', body_style)],
                [Paragraph(f'Line: {bug.get("line","N/A")} — {bug.get("description","")}', body_style)],
                [Paragraph(f'<i>Fix: {bug.get("suggestion","")}</i>', body_style)],
            ]
            t = Table(data, colWidths=[17*cm])
            t.setStyle(TableStyle([("BOX", (0,0), (-1,-1), 0.5, color), ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#fef2f2")), ("PADDING", (0,0), (-1,-1), 6)]))
            story.append(t)
            story.append(Spacer(1, 0.2*cm))

    # Security Issues
    sec = review.get("security_issues", [])
    if sec:
        story.append(Paragraph(f"Security Issues ({len(sec)} found)", heading_style))
        for s in sec:
            sev = s.get("severity", "medium").lower()
            color = SEVERITY_COLORS.get(sev, colors.gray)
            data = [
                [Paragraph(f'<b>[{sev.upper()}] {s.get("issue","")}</b>', body_style)],
                [Paragraph(s.get("recommendation",""), body_style)],
            ]
            t = Table(data, colWidths=[17*cm])
            t.setStyle(TableStyle([("BOX", (0,0), (-1,-1), 0.5, color), ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#fff7ed")), ("PADDING", (0,0), (-1,-1), 6)]))
            story.append(t)
            story.append(Spacer(1, 0.2*cm))

    # Performance
    perf = review.get("performance_issues", [])
    if perf:
        story.append(Paragraph(f"Performance Issues ({len(perf)} found)", heading_style))
        for p in perf:
            story.append(Paragraph(f"• <b>{p.get('description','')}</b>", body_style))
            story.append(Paragraph(f"  → {p.get('recommendation','')}", body_style))
            story.append(Spacer(1, 0.1*cm))

    # Suggestions
    sugg = review.get("suggestions", [])
    if sugg:
        story.append(Paragraph(f"Code Quality Suggestions ({len(sugg)})", heading_style))
        for s in sugg:
            story.append(Paragraph(f"• [{s.get('category','').upper()}] {s.get('description','')}", body_style))

    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.grey, spaceBefore=12))
    story.append(Paragraph("Generated by AI Code Review & Bug Prediction System", ParagraphStyle("Footer", parent=styles["Normal"], fontSize=8, textColor=colors.grey, alignment=TA_CENTER)))

    doc.build(story)
    return buffer.getvalue()
